// JSON-LD builders. Each takes the same data the page renders. Step 0.8 adds
// Organization, SoftwareApplication, Offer, BreadcrumbList and HowTo.

export function faqPage(items: { question: string; answer: string }[]) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: items.map((i) => ({
      '@type': 'Question',
      name: i.question,
      acceptedAnswer: { '@type': 'Answer', text: i.answer },
    })),
  };
}
